import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.dirname(fileURLToPath(import.meta.url));
const files = fs.readdirSync(path.join(root, 'migrations')).filter(f => /^\d{3}_.*\.sql$/.test(f)).sort();
const normalize = text => text.replace(/\r\n/g, '\n');
const literal = value => `'${value.replaceAll("'", "''")}'`;
const read = file => normalize(fs.readFileSync(path.join(root, file), 'utf8'));
let output = `-- GENERATED by node supabase/build-installer.mjs. Do not edit this file directly.
-- schema.sql, seed.sql, supabase_production_schema.sql and migrations/all.sql
-- are identical compatibility entry points. Run ANY ONE complete file.
-- Re-running is supported. Existing staff, passwords and identity UUIDs are preserved.
-- Bigint row IDs stay intact; employee/user reference columns use stable UUIDs.
-- Historical numbered migrations are upgrade steps, NOT independent installers.
-- Back up a production database before any schema upgrade.
BEGIN;
${read('installer/preflight.sql')}
`;

for (const file of files) {
  const version = file.slice(0, 3);
  const original = read(`migrations/${file}`);
  const body = original.replace(/^(?:BEGIN|COMMIT);[ \t]*$/gm, '');
  const checksum = createHash('sha256').update(original).digest('hex');
  const tag = `$migration_${version}$`;
  if (body.includes(tag)) throw new Error(`SQL delimiter collision: ${file}`);
  output += `
-- ${file}
DO $install_${version}$
BEGIN
  IF EXISTS (SELECT 1 FROM private.edgewforce_migrations WHERE version = '${version}' AND checksum <> '${checksum}') THEN
    RAISE EXCEPTION 'Migration ${version} was edited after installation. Use a new numbered migration; no changes were committed.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM private.edgewforce_migrations WHERE version = '${version}') THEN
    IF (${Number(version)} <= (SELECT adopt_through FROM edgewforce_install_state))
       OR ('${version}' = '006' AND (SELECT preserve_existing_staff FROM edgewforce_install_state)) THEN
      INSERT INTO private.edgewforce_migrations(version, name, checksum, source)
      VALUES ('${version}', ${literal(file)}, '${checksum}', 'adopted');
    ELSE
      EXECUTE ${tag}
${body}
${tag};
      INSERT INTO private.edgewforce_migrations(version, name, checksum, source)
      VALUES ('${version}', ${literal(file)}, '${checksum}', 'applied');
    END IF;
  END IF;
END;
$install_${version}$;
`;
}

const references = [...read('migrations/012_uuid_identity_references_global.sql').matchAll(/SELECT private\.convert_identity_reference_to_uuid\('public\.([^']+)', '([^']+)', '([^']+)'\);/g)]
  .map(([, table, column, parent]) => [table, column, parent]);
if (references.length < 40) throw new Error('Identity reference manifest is incomplete');
references.push(['employee_location_assignments', 'employee_id', 'employees'], ['location_assignment_history', 'employee_id', 'employees'], ['task_reminders', 'employee_id', 'employees'], ['task_reminders', 'user_id', 'users']);
output += `
-- Validate the identity contract before committing, including adopted databases.
DO $verify$
DECLARE
  ref RECORD;
  actual_type TEXT;
  orphan_count BIGINT;
BEGIN
  FOR ref IN SELECT * FROM (VALUES
    ${references.map(row => `(${row.map(literal).join(', ')})`).join(',\n    ')}
  ) AS refs(table_name, column_name, parent_table)
  LOOP
    SELECT data_type INTO actual_type FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = ref.table_name AND column_name = ref.column_name;
    IF actual_type IS NULL THEN CONTINUE; END IF;
    IF actual_type <> 'uuid' THEN
      RAISE EXCEPTION 'Identity contract mismatch: %.% must be uuid, found %. No changes were committed.', ref.table_name, ref.column_name, actual_type;
    END IF;
    EXECUTE format('SELECT count(*) FROM public.%I child LEFT JOIN public.%I parent ON child.%I = parent.uuid WHERE child.%I IS NOT NULL AND parent.uuid IS NULL', ref.table_name, ref.parent_table, ref.column_name, ref.column_name) INTO orphan_count;
    IF orphan_count <> 0 THEN
      RAISE EXCEPTION 'Unmapped identities in %.%: % row(s). No changes were committed; data must be reconciled, not cast.', ref.table_name, ref.column_name, orphan_count;
    END IF;
  END LOOP;
END;
$verify$;
NOTIFY pgrst, 'reload schema';
COMMIT;
SELECT 'EdgeWForce database ready' AS status,
       (SELECT count(*) FROM public.employees) AS staff_count,
       (SELECT count(*) FROM private.edgewforce_migrations) AS migrations_recorded;
`;

for (const file of ['schema.sql', 'seed.sql', 'supabase_production_schema.sql', 'migrations/all.sql']) {
  if (process.argv.includes('--check')) {
    if (read(file) !== output) throw new Error(`${file} is stale. Run node supabase/build-installer.mjs`);
  } else fs.writeFileSync(path.join(root, file), output);
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} four identical installers from ${files.length} versioned migrations.`);
